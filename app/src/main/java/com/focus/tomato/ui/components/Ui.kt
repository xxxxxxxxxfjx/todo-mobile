}

fun formatFocusDuration(seconds: Long): String {
    if (seconds <= 0) return "0m"
    val h = seconds / 3600
    val m = (seconds % 3600) / 60
    return when {
        h > 0 && m > 0 -> "${h}h ${m}m"
        h > 0 -> "${h}h"
        m > 0 -> "${m}m"
        else -> "<1m"
    }
}

fun formatClock(millis: Long): String {
    val total = (millis.coerceAtLeast(0L) + 999) / 1000
    val h = total / 3600
    val m = (total % 3600) / 60
    val s = total % 60
    return if (h > 0) {
        String.format(Locale.getDefault(), "%d:%02d:%02d", h, m, s)
    } else {
        String.format(Locale.getDefault(), "%02d:%02d", m, s)
    }
}

fun todayLabel(): String {
    val date = LocalDate.now()
    val weekdays = arrayOf("周一", "周二", "周三", "周四", "周五", "周六", "周日")
    val formatter = DateTimeFormatter.ofPattern("M月d日", Locale.CHINA)
    return "${date.format(formatter)} · ${weekdays[date.dayOfWeek.value - 1]}"
}

fun weekdayLabel(date: LocalDate): String {
    val weekdays = arrayOf("一", "二", "三", "四", "五", "六", "日")
    return weekdays[date.dayOfWeek.value - 1]
}
